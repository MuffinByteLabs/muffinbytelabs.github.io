/* Writes src/content/index.ts — one lazy import per published Field Note.

   The post page used to load its body with `import(`@/content/${slug}.mdx`)`.
   A template-literal import cannot be resolved ahead of time, so the bundler
   pulls in EVERY .mdx file that could match: under `next dev` the first post
   anyone opened paid to compile all of them (~8 s cold). An explicit map of
   `() => import("./slug.mdx")` lets the bundler compile only the post being
   opened.

   Runs automatically before `npm run dev` and `npm run build` (the predev /
   prebuild scripts), so a new post never needs a manual step. Drafts are
   left out, so they are never compiled into the production build. */

const fs = require("fs");
const path = require("path");
const matter = require("gray-matter");

const CONTENT = path.join(process.cwd(), "src/content");
const OUT = path.join(CONTENT, "index.ts");

const slugs = fs
  .readdirSync(CONTENT)
  .filter((f) => f.endsWith(".mdx"))
  .filter((f) => matter(fs.readFileSync(path.join(CONTENT, f), "utf-8")).data.draft !== true)
  .map((f) => f.replace(/\.mdx$/, ""))
  .sort();

const body = [
  "/* GENERATED by scripts/gen-post-index.cjs — do not hand-edit.",
  "   One lazy import per published post, so opening a post compiles only",
  "   that post. Regenerated before every `npm run dev` and `npm run build`. */",
  "",
  'import type { ComponentType } from "react";',
  "",
  "export const POSTS: Record<string, () => Promise<{ default: ComponentType }>> = {",
  ...slugs.map((s) => `  "${s}": () => import("./${s}.mdx"),`),
  "};",
  "",
].join("\n");

/* only touch the file when it changes, so a running dev server does not
   see a no-op write as an edit */
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf-8") : "";
if (prev !== body) {
  fs.writeFileSync(OUT, body);
  console.log(`gen-post-index: ${slugs.length} posts → src/content/index.ts`);
}
